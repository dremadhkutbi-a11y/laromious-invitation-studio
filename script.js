function parseDateValue(rawValue) {
  const raw = normalizeDigits(rawValue).trim();
  if (!raw) return null;

  let day;
  let month;
  let year;
  const isoMatch = raw.match(/^(\d{4})-(\d{1,2})-(\d{1,2})$/);
  if (isoMatch) {
    year = Number(isoMatch[1]);
    month = Number(isoMatch[2]);
    day = Number(isoMatch[3]);
  } else {
    const parts = raw.split(/[./\-\s]+/).filter(Boolean).map(Number);
    if (parts.length !== 3 || parts.some((part) => !Number.isFinite(part))) return null;
    if (String(parts[0]).length === 4) {
      year = parts[0];
      month = parts[1];
      day = parts[2];
    } else {
      day = parts[0];
      month = parts[1];
      year = parts[2];
    }
  }

  if (year < 100) year += 2000;
  if (year < 1900 || year > 2200 || month < 1 || month > 12 || day < 1 || day > 31) return null;

  const date = new Date(year, month - 1, day);
  if (date.getFullYear() !== year || date.getMonth() !== month - 1 || date.getDate() !== day) return null;
  return date;
}

function parseTimeValue(rawValue) {
  const raw = normalizeDigits(rawValue).trim().toLowerCase().replace(/\s+/g, " ");
  if (!raw) return null;

  const hasPm = /(?:pm|p\.m\.|مساء|مسا)/i.test(raw);
  const hasAm = /(?:am|a\.m\.|صباح|صبا)/i.test(raw);
  const match = raw.match(/(\d{1,2})(?:\s*[:٫.]\s*(\d{1,2}))?/);
  if (!match) return null;

  let hour = Number(match[1]);
  const minute = match[2] === undefined ? 0 : Number(match[2]);
  if (!Number.isFinite(hour) || !Number.isFinite(minute) || minute > 59) return null;

  if (hasPm || hasAm) {
    if (hour < 1 || hour > 12) return null;
    if (hasPm && hour < 12) hour += 12;
    if (hasAm && hour === 12) hour = 0;
  } else if (hour > 23) {
    return null;
  }

  return { hour, minute };
}

function formatArabicDate(date) {
  return new Intl.DateTimeFormat("ar-SA-u-ca-gregory", {
    weekday: "long",
    day: "numeric",
    month: "long",
    year: "numeric",
  }).format(date);
}

function formatArabicTime(time) {
  const hour12 = time.hour % 12 || 12;
  const suffix = time.hour >= 12 ? "مساءً" : "صباحًا";
  const minutes = time.minute ? `:${toArabicDigits(String(time.minute).padStart(2, "0"))}` : "";
  return `${toArabicDigits(hour12)}${minutes} ${suffix}`;
}

function formatEditorDate(isoValue) {
  const date = parseDateValue(isoValue);
  if (!date) return isoValue;
  const western = `${String(date.getDate()).padStart(2, "0")} / ${String(date.getMonth() + 1).padStart(2, "0")} / ${date.getFullYear()}`;
  return state.lang === "ar" ? toArabicDigits(western) : western;
}

function formatEditorTime(timeValue) {
  const [hour, minute] = timeValue.split(":").map(Number);
  if (!Number.isFinite(hour) || !Number.isFinite(minute)) return timeValue;
  if (state.lang === "en") {
    const hour12 = hour % 12 || 12;
    return `${hour12}:${String(minute).padStart(2, "0")} ${hour >= 12 ? "PM" : "AM"}`;
  }
  return formatArabicTime({ hour, minute });
}

