function normalizeDigits(value) {
  return String(value || "")
    .replace(/[٠-٩]/g, (digit) => String("٠١٢٣٤٥٦٧٨٩".indexOf(digit)))
    .replace(/[۰-۹]/g, (digit) => String("۰۱۲۳۴۵۶۷۸۹".indexOf(digit)));
}

function toArabicDigits(value) {
  return String(value).replace(/\d/g, (digit) => "٠١٢٣٤٥٦٧٨٩"[digit]);
}

function updateInterfaceLanguage() {
  document.documentElement.lang = state.lang;
  document.documentElement.dir = state.lang === "ar" ? "rtl" : "ltr";

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (COPY[state.lang][key]) element.textContent = COPY[state.lang][key];
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    if (COPY[state.lang][key]) element.placeholder = COPY[state.lang][key];
  });

  document.getElementById("openDatePicker").setAttribute("aria-label", copy("pickerDateLabel"));
  document.getElementById("openTimePicker").setAttribute("aria-label", copy("pickerTimeLabel"));
  refs.closePreviewButton.setAttribute("aria-label", copy("dialogClose"));

  document.querySelectorAll(".language-button").forEach((button) => {
    button.classList.toggle("is-active", button.dataset.language === state.lang);
    button.setAttribute("aria-pressed", button.dataset.language === state.lang ? "true" : "false");
  });

  if (refs.eventDatePicker.value) refs.eventDateText.value = formatEditorDate(refs.eventDatePicker.value);
  if (refs.eventTimePicker.value) refs.eventTimeText.value = formatEditorTime(refs.eventTimePicker.value);

  refs.descriptionCount.textContent = `${refs.eventDescription.value.length} / ${DESCRIPTION_LIMIT}`;
  updatePreview();
}

