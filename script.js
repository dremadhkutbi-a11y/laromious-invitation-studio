function transliterate(value) {
  const map = {
    ا: "a", أ: "a", إ: "i", آ: "a", ب: "b", ت: "t", ث: "th", ج: "j", ح: "h", خ: "kh", د: "d", ذ: "dh", ر: "r", ز: "z", س: "s", ش: "sh", ص: "s", ض: "d", ط: "t", ظ: "z", ع: "a", غ: "gh", ف: "f", ق: "q", ك: "k", ل: "l", م: "m", ن: "n", ه: "h", و: "w", ي: "y", ى: "a", ة: "h", ئ: "y", ء: "a", ـ: "",
  };
  return String(value || "")
    .normalize("NFKD")
    .split("")
    .map((character) => map[character] || character)
    .join("");
}

function safeFileName(name) {
  const slug = transliterate(name)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
    .slice(0, 48);
  return `invitation-${slug || "guest"}.png`;
}

